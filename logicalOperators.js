// Logical Operators:
// && (and)
// true && true = true
// true && false = false
// false && false = false

// || (or)
// true || true = true
// true || false = true
// false || false = false
// sidenote: there's just a logical operator as XOR
//   XOR means "exclusive or" one or the other must be true but not both

// ! (not)
// reverses truth value
// !true = false
// !false = true